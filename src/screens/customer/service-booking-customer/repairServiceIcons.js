// Icon component for one repair service/problem tile.
export function getRepairServiceIcon(serviceName, groupCode, groupName) {
  const { name } = resolveServiceIconName(serviceName, groupCode, groupName);
  return ICONS[name] || ICONS[DEFAULT_ICON];
}
